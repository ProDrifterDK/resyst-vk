#!/usr/bin/env python3
"""Genera assets/js/lexicon.js a partir de lexicon-src/ (FrequencyWords, MIT).

Toma las N palabras más frecuentes de cada idioma, filtrando a letras simples
(sin números, apóstrofes ni guiones) para el predictor offline del teclado.
Fuente: https://github.com/hermitdave/FrequencyWords (OpenSubtitles 2018).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "lexicon-src"
OUT = ROOT / "assets" / "js" / "lexicon.js"

COUNTS = {"es": 12000, "en": 8000}
ALLOWED = {"es": re.compile(r"^[a-záéíóúüñ]+$"), "en": re.compile(r"^[a-z]+$")}
# La letra ñ no existe en inglés; evita sugerencias basura.
BANNED = {"en": "ñ"}


def main():
    parts = [
        "/* GENERATED by tools/gen_lexicon.py — no editar a mano.",
        " * Fuente: FrequencyWords (OpenSubtitles 2018), MIT License.",
        " * lexicon-src/LICENSE. es=%d en=%d palabras más frecuentes. */" % (
            COUNTS["es"], COUNTS["en"]),
        "'use strict';",
        "window.VK = window.VK || {};",
        "VK.LEXICON = {",
    ]
    for lang, n in COUNTS.items():
        words, seen = [], set()
        rx = ALLOWED[lang]
        with open(SRC / f"{lang}_50k.txt", encoding="utf-8") as fh:
            for line in fh:
                w = line.split()[0].lower()
                if not rx.match(w):
                    continue
                if any(ch in w for ch in BANNED.get(lang, "")):
                    continue
                if w in seen:
                    continue
                seen.add(w)
                words.append(w)
                if len(words) >= n:
                    break
        if len(words) < n:
            print(f"AVISO {lang}: solo {len(words)} palabras", file=sys.stderr)
        quoted = [f'"{w}"' for w in words]
        # filas de ~100 palabras para diffs legibles
        pretty = ",\n  ".join(",".join(quoted[i:i + 100]) for i in range(0, len(quoted), 100))
        parts.append(f'"{lang}": [\n  {pretty}\n],')
    parts[-1] = parts[-1].rstrip(",")
    parts.append("};")
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"OK {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
